import asyncio
import os
import sys
import time
from playwright.async_api import async_playwright

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace', line_buffering=True)
    sys.stderr.reconfigure(encoding='utf-8', errors='replace', line_buffering=True)
except Exception:
    pass

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
COOKIES_TXT = os.path.join(SCRIPT_DIR, "tiktok_cookies.txt")

async def login_tiktok():
    print("==================================================")
    print("   DANG NHAP TIKTOK DE MO KHOA TAI TAT CA VIDEO")
    print("   Trinh duyet Chrome se mo ra.")
    print("   Ban hay dang nhap vao tai khoan TikTok cua ban")
    print("   (Quet ma QR tren app, hoac dang nhap Google/SDT).")
    print("   He thong se tu dong luu cookie vao tiktok_cookies.txt!")
    print("==================================================")

    async with async_playwright() as p:
        browser = await p.chromium.launch(
            headless=False,
            args=['--disable-blink-features=AutomationControlled']
        )
        context = await browser.new_context(
            viewport={'width': 1280, 'height': 850}
        )
        page = await context.new_page()
        await page.goto("https://www.tiktok.com/login", wait_until="domcontentloaded")

        print("\nDang cho ban dang nhap tren man hinh trinh duyet (cho toi da 5 phut)...")
        logged_in = False
        for _ in range(300):
            cookies = await context.cookies()
            cookie_dict = {c['name']: c['value'] for c in cookies}
            if 'sessionid' in cookie_dict or 'sessionid_ss' in cookie_dict or 'sid_guard' in cookie_dict or 'sid_tt' in cookie_dict:
                print("\n[THANH CONG] Da phat hien dang nhap TikTok thanh cong!")
                
                with open(COOKIES_TXT, "w", encoding="utf-8") as f:
                    f.write("# Netscape HTTP Cookie File\n")
                    f.write("# Generated by login_tiktok_helper.py\n")
                    for c in cookies:
                        domain = c.get('domain', '.tiktok.com')
                        include_sub = "TRUE" if domain.startswith('.') else "FALSE"
                        path = c.get('path', '/')
                        secure = "TRUE" if c.get('secure', False) else "FALSE"
                        exp = c.get('expires', -1)
                        if exp is None or exp <= 0:
                            exp = int(time.time() + 86400 * 365)
                        else:
                            exp = int(exp)
                        name = c.get('name', '')
                        value = c.get('value', '')
                        if name:
                            f.write(f"{domain}\t{include_sub}\t{path}\t{secure}\t{exp}\t{name}\t{value}\n")

                print(f"Da luu phien dang nhap vao: tiktok_cookies.txt")
                print("Tu bay gio ban co the tai tat ca video va phim ngan tren TikTok!")
                logged_in = True
                await asyncio.sleep(2)
                break
            await asyncio.sleep(1)

        if not logged_in:
            print("[CANH BAO] Het thoi gian cho dang nhap (5 phut).")

        await browser.close()

if __name__ == "__main__":
    asyncio.run(login_tiktok())

